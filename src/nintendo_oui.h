#define NINTENDO_OUI_COUNT (sizeof(NINTENDO_OUIS) / sizeof(NINTENDO_OUIS[0]))

static inline bool is_nintendo_mac(const uint8_t mac[6])
{
    size_t i;
    for (i = 0; i < NINTENDO_OUI_COUNT; i++) {
        if (memcmp(mac, NINTENDO_OUIS[i], 3) == 0) return true;
    }
    return false;
}

